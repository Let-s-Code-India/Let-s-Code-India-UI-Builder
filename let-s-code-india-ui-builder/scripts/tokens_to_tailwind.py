#!/usr/bin/env python3
"""tokens_to_tailwind.py - emit a Tailwind CSS v4 theme (CSS variables + @theme) with
dark and light modes, from a shipped palette id or from one brand colour.

Examples
  python3 scripts/tokens_to_tailwind.py --palette cyber-black-green --out src/theme.css
  python3 scripts/tokens_to_tailwind.py --palette clean-minimalist-saas --default system
  python3 scripts/tokens_to_tailwind.py --brand "#7C3AED" --mode dark --name my-app
  python3 scripts/tokens_to_tailwind.py --list

--default native  (default) palette's own mode is the default; add data-theme="light|dark" on <html> to switch.
--default system  follow the OS (prefers-color-scheme); data-theme still overrides it.

The result is verified with the same contrast rules as the shipped palettes before it is written.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from colorlib import (TOKEN_ORDER, derive_tokens, from_hsl, norm, to_hsl,  # noqa: E402
                      twin_seeds, verify_tokens)

ROOT = Path(__file__).resolve().parent.parent
PALETTES = ROOT / "assets/tokens/palettes.json"


def decls(tokens: dict, extra: dict | None = None, ind: str = "  ") -> str:
    rows = [f"{ind}--{k}: {tokens[k]};" for k in TOKEN_ORDER]
    rows += [f"{ind}--{k}: {v};" for k, v in (extra or {}).items()]
    return "\n".join(rows)


def from_brand(brand: str, mode: str):
    """Derive both themes from one brand colour. Returns (modes, label)."""
    brand = norm(brand)
    h, s, _ = to_hsl(brand)
    s_bg = min(max(s * 0.35, 0.06), 0.30)
    if mode == "dark":
        canvas, surface = from_hsl(h, s_bg, 0.07), from_hsl(h, s_bg, 0.105)
    else:
        canvas, surface = from_hsl(h, s_bg * 0.5, 0.955), "#FFFFFF"
    native, _ = derive_tokens(canvas, surface, brand, mode)
    tw_canvas, tw_surface, tw_accent, other = twin_seeds(canvas, mode, brand)
    twin, _ = derive_tokens(tw_canvas, tw_surface, tw_accent, other)
    return {mode: native, other: twin}, f"brand {brand}"


def render(modes: dict, native: str, label: str, default: str, extra: dict) -> str:
    other = "light" if native == "dark" else "dark"
    out = [f"/* theme.css - generated by scripts/tokens_to_tailwind.py ({label}).",
           "   Regenerate instead of editing values by hand: every pair is contrast-verified. */", ""]
    if default == "system":
        out += [":root {", "  color-scheme: light dark;", decls(modes["light"], extra), "}",
                "@media (prefers-color-scheme: dark) {",
                "  :root:not([data-theme=\"light\"]) {", decls(modes["dark"], extra, "    "), "  }", "}",
                ":root[data-theme=\"light\"] {", "  color-scheme: light;", decls(modes["light"], extra), "}",
                ":root[data-theme=\"dark\"] {", "  color-scheme: dark;", decls(modes["dark"], extra), "}"]
    else:
        out += [":root {", f"  color-scheme: {native};", decls(modes[native], extra), "}",
                f":root[data-theme=\"{native}\"] {{", f"  color-scheme: {native};", decls(modes[native], extra), "}",
                f":root[data-theme=\"{other}\"] {{", f"  color-scheme: {other};", decls(modes[other], extra), "}"]
    names = list(TOKEN_ORDER) + list(extra)
    out += ["", "/* Tailwind v4: tokens become utilities, e.g. bg-canvas text-fg border-line bg-accent text-accent-fg */",
            "@theme inline {"]
    out += [f"  --color-{n}: var(--{n});" for n in names]
    out += ["}", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--palette", help="palette id from references/palettes.md")
    ap.add_argument("--brand", help="brand colour hex; derives a full theme")
    ap.add_argument("--mode", choices=["dark", "light"], default="dark", help="native mode for --brand")
    ap.add_argument("--name", default="brand", help="label used in the header comment for --brand")
    ap.add_argument("--default", choices=["native", "system"], default="native")
    ap.add_argument("--out", help="write to this file instead of stdout")
    ap.add_argument("--list", action="store_true", help="list palette ids")
    a = ap.parse_args()

    data = json.loads(PALETTES.read_text(encoding="utf-8"))
    if a.list:
        for p in data["palettes"]:
            print(f"{p['n']:02d} {p['id']:<26} {p['native']:<5} {p['mood']}")
        return 0

    extra: dict = {}
    if a.palette:
        pal = next((p for p in data["palettes"] if p["id"] == a.palette or f"{p['n']:02d}" == a.palette), None)
        if not pal:
            print(f"unknown palette {a.palette!r}; run with --list", file=sys.stderr)
            return 2
        modes, native, label, extra = pal["modes"], pal["native"], f"palette {pal['n']:02d} {pal['id']}", pal["extra"]
    elif a.brand:
        modes, label = from_brand(a.brand, a.mode)
        native = a.mode
        label = f"{label}, {a.name}"
    else:
        ap.print_help()
        return 2

    for mode, tk in modes.items():
        bad = verify_tokens(tk)
        if bad:
            print(f"refusing to write: {mode} theme fails contrast: {'; '.join(bad)}", file=sys.stderr)
            return 1

    css = render(modes, native, label, a.default, extra)
    if a.out:
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(css, encoding="utf-8")
        print(f"wrote {a.out} ({label}, default={a.default})")
    else:
        sys.stdout.write(css)
    return 0


if __name__ == "__main__":
    sys.exit(main())
